-- 1. Bảng dilinh_users (Quản lý tài khoản Admin/Thành viên)
CREATE TABLE IF NOT EXISTS dilinh_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nick_name TEXT UNIQUE NOT NULL,
    pass TEXT NOT NULL,
    full_name TEXT,
    user_role TEXT DEFAULT 'user',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Bảng dilinh_product (Quản lý sản phẩm đặc sản)
CREATE TABLE IF NOT EXISTS dilinh_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code TEXT UNIQUE NOT NULL,
    product_long TEXT NOT NULL,
    sale_price INTEGER DEFAULT 0 NOT NULL,
    promo_price INTEGER DEFAULT 0,
    image TEXT,
    status BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Bảng dilinh_posts (Quản lý bài viết blog, tin tức và testimonial của khách hàng)
CREATE TABLE IF NOT EXISTS dilinh_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT UNIQUE,
    content TEXT,
    thumbnail TEXT,
    post_type TEXT DEFAULT 'article' NOT NULL, -- 'article', 'testimonial', 'event', 'promotion'
    status BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Bảng dilinh_app_settings (Quản lý cấu hình toàn trang, layout giao diện, menu, thông tin shop)
CREATE TABLE IF NOT EXISTS dilinh_app_settings (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    description TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

