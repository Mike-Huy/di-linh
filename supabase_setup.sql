ON CONFLICT (id) DO NOTHING;

-- 2. Gỡ bỏ mọi chính sách giới hạn trên storage.objects của bucket "dilinh" để Admin upload thoải mái
DROP POLICY IF EXISTS "Allow public CRUD on dilinh bucket" ON storage.objects;
CREATE POLICY "Allow public CRUD on dilinh bucket"
ON storage.objects FOR ALL TO public
USING (bucket_id = 'dilinh')
WITH CHECK (bucket_id = 'dilinh');


